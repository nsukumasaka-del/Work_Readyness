import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { webcrypto } from 'node:crypto';
const require = createRequire(import.meta.url);
const { build } = require('../artifacts/api-server/node_modules/esbuild');
const source = readFileSync('workers/d1/career.ts', 'utf8');
const dependencies = new Map([...source.matchAll(/import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["']/g)].map(match => [match[2], match[1].split(',').map(name => name.trim()).filter(name => name && !name.startsWith('type '))]));
const bundle = await build({ entryPoints: ['workers/d1/career.ts'], bundle: true, write: false, platform: 'node', format: 'cjs', plugins: [{ name: 'mock-services', setup(builder) {
  builder.onResolve({ filter: /.*/ }, args => args.importer.endsWith('career.ts') && dependencies.has(args.path) ? { path: args.path, namespace: 'mock' } : undefined);
  builder.onLoad({ filter: /.*/, namespace: 'mock' }, args => ({ contents: dependencies.get(args.path).map(name => `export const ${name} = ${name === 'getAuthenticatedUser' ? 'async () => globalThis.shareTestUser' : '() => ({})'};`).join('\n'), loader: 'js' }));
} }] });
const module = { exports: {} };
new Function('module', 'exports', 'require', 'crypto', bundle.outputFiles[0].text)(module, module.exports, require, webcrypto);
const { handleD1Career } = module.exports;
const shares = new Map();
const row = { id: 1, title: 'Sample CV', content_json: JSON.stringify({ fullName: 'Sample Candidate', references: ['Referee'] }) };
const env = { DB: { prepare(sql) {
  let values;
  return { bind(...args) { values = args; return this; }, async first() {
    if (sql.includes('JOIN cv_shares')) return shares.has(values[0]) && shares.get(values[0]) > values[1] ? row : null;
    if (sql.includes('career_profiles')) return { id: 1, name: 'Candidate' };
    if (sql.includes('generated_cvs')) return values[0] === 1 && values[1] === 'owner' ? row : null;
    throw new Error('Unexpected query: ' + sql);
  }, async run() { assert.match(sql, /INSERT INTO cv_shares/); shares.set(values[0], values[2]); return {}; } };
} } };
const request = (path, method = 'GET') => new Request('https://www.bonlist.site/api/career/cv/' + path, { method });
globalThis.shareTestUser = null;
assert.equal((await handleD1Career(request('documents/1/share', 'POST'), env)).status, 401);
globalThis.shareTestUser = { id: 'other-owner' };
assert.equal((await handleD1Career(request('documents/1/share', 'POST'), env)).status, 404);
globalThis.shareTestUser = { id: 'owner' };
const response = await handleD1Career(request('documents/1/share', 'POST'), env);
assert.equal(response.status, 200);
const { url, expiresAt } = await response.json();
const token = url.split('/').pop();
assert.match(token, /^[a-f0-9]{64}$/);
assert.ok(Math.abs(Date.parse(expiresAt) - Date.now() - 30 * 86400000) < 5000);
globalThis.shareTestUser = null;
const publicResponse = await handleD1Career(request('shared/' + token), env);
assert.equal(publicResponse.status, 200);
assert.equal(publicResponse.headers.get('Cache-Control'), 'no-store');
assert.equal((await publicResponse.json()).document.references[0], 'Referee');
assert.equal((await handleD1Career(request('shared/' + token, 'DELETE'), env)).status, 405);
shares.set(token, '2000-01-01T00:00:00.000Z');
assert.equal((await handleD1Career(request('shared/' + token), env)).status, 404);
console.log('CV share access: authentication, ownership, token format, expiry and read-only access passed.');
const routing = await build({ entryPoints: ['workers/public-html.ts'], bundle: true, write: false, platform: 'node', format: 'cjs' });
const routeModule = { exports: {} };
new Function('module', 'exports', 'require', routing.outputFiles[0].text)(routeModule, routeModule.exports, require);
const html = routeModule.exports.renderRouteHtml('<html><head><title>BonList</title></head><body><div id="root"></div></body></html>', '/shared-cv/' + token);
assert.equal(html.status, 200);
assert.equal(html.noIndex, true);
assert.equal(html.robots, 'noindex, nofollow');
console.log('Shared CV Cloudflare HTML routing: HTTP 200 and no-index passed.');
